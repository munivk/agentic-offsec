"""
Compute the evaluation table from evidence_clean/. Every number in ANALYSIS.md and
EVALUATION.md comes from this script's output (evidence_clean/TABLE.md).

Usage: python evidence_table.py [evidence_dir]
Cost assumes Bedrock on-demand Sonnet pricing: $3 / 1M input, $15 / 1M output tokens.
"""
import json, re, sys, glob, os
from datetime import datetime

D = sys.argv[1] if len(sys.argv) > 1 else "evidence_clean"
IN_PRICE, OUT_PRICE = 3 / 1e6, 15 / 1e6
SEV = r"(CRITICAL|HIGH|MEDIUM|LOW|INFO)"


def ts(r):
    return datetime.fromisoformat(r["ts"])


def severity_for(report, keyword):
    """Severity the report assigned to the finding whose title/WHAT mentions keyword.
    Reports number findings either as 'Finding N -- SEV -- title' or as '1. SEVERITY: x'
    blocks, so split into blocks and look at each block's first lines."""
    lines = report.splitlines()
    starts = [i for i, l in enumerate(lines)
              if re.match(r"\s*(#+\s*)?(\*\*)?(Finding\s+\d+|\d+[.)]\s)", l, re.I)]
    for k, s in enumerate(starts):
        block = lines[s:(starts[k + 1] if k + 1 < len(starts) else len(lines))]
        head = " ".join(block[:3]).lower()
        if keyword in head:
            m = re.search(SEV, " ".join(block[:3]).upper())
            return m.group(1) if m else "?"
    return None  # not reported as a finding


rows, base = [], []
for p in sorted(glob.glob(f"{D}/audit_[0-9]*.jsonl")):
    n = re.search(r"audit_(\d+)", p).group(1)
    recs = [json.loads(l) for l in open(p)]
    calls = [r for r in recs if r["event"] == "tool_call"]
    results = [r for r in recs if r["event"] == "tool_result"]
    gates = [r for r in recs if r["event"] == "impact_gate"]
    usage = [r["usage"] for r in recs if r["event"] == "llm_usage" and r.get("usage")]
    tin = sum(u.get("inputTokens", 0) for u in usage)
    tout = sum(u.get("outputTokens", 0) for u in usage)
    tids = set()
    for r in results:
        tids.update(r["summary"].get("template_ids") or [])
    rep_path = f"{D}/report_{n}.md"
    report = open(rep_path).read() if os.path.exists(rep_path) else ""
    rows.append({
        "run": n,
        "calls": len(calls),
        "nuclei_calls": sum(c["tool"] == "run_nuclei" for c in calls),
        "timeouts": sum(r["summary"].get("status") == "timeout" for r in results),
        "tags_per_call": [c["input"].get("tags") for c in calls if c["tool"] == "run_nuclei"],
        "gate": {f'{g["level"]}/{g["decision"]}': 0 for g in gates},
        "raw_findings": sum((r["summary"].get("count") or 0) for r in results
                            if r["tool"] == "run_nuclei"),
        "scan_found_metrics": "prometheus-metrics" in tids,
        "scan_found_swagger": any("swagger" in (t or "") for t in tids),
        "sev_metrics": severity_for(report, "metric"),
        "sev_swagger": severity_for(report, "swagger"),
        "tokens_in": tin, "tokens_out": tout,
        "cost_usd": round(tin * IN_PRICE + tout * OUT_PRICE, 4),
        "wall_min": round((ts(recs[-1]) - ts(recs[0])).total_seconds() / 60, 1),
        "forced_report": any(r["event"] == "max_steps_reached" for r in recs),
    })
    for g in gates:
        rows[-1]["gate"][f'{g["level"]}/{g["decision"]}'] += 1

for p in sorted(glob.glob(f"{D}/baseline_*.json")):
    b = json.load(open(p))
    b["run"] = re.search(r"baseline_(\d+)", p).group(1)
    base.append(b)


def agree(key):
    vals = [r[key] or "not reported" for r in rows]
    if not vals:
        return "no runs"
    top = max(set(vals), key=vals.count)
    return f"{vals.count(top)} of {len(vals)} runs gave {top} (all: {', '.join(vals)})"


out = ["# Evidence table (generated by evidence_table.py)", ""]
meta = f"{D}/_meta.txt"
if os.path.exists(meta):
    out += ["```", open(meta).read().strip(), "```", ""]
fps = {}
for p in sorted(glob.glob(f"{D}/audit_*.jsonl")):
    first = json.loads(open(p).readline())
    fps[os.path.basename(p)] = first.get("meta", {}).get("code_sha256", "(none: no model run)")
model_fps = {v for v in fps.values() if not v.startswith("(")}
out += [f"Code fingerprint in the agent audit logs: "
        + ("one value, " + next(iter(model_fps)) if len(model_fps) == 1 else f"{len(model_fps)} DIFFERENT values: {fps}"),
        ""]
out += ["## Agent runs", "",
        "| Run | Calls | Nuclei calls | Timeouts | Raw findings | Scan found /metrics | Scan found Swagger | /metrics severity | Swagger severity | Gate decisions | Tokens in/out | Cost | Wall-clock | Forced report |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    g = ", ".join(f"{k} x{v}" for k, v in sorted(r["gate"].items()))
    out.append(f'| {r["run"]} | {r["calls"]} | {r["nuclei_calls"]} | {r["timeouts"]} | {r["raw_findings"]} | '
               f'{"Y" if r["scan_found_metrics"] else "N"} | {"Y" if r["scan_found_swagger"] else "N"} | '
               f'{r["sev_metrics"] or "not reported"} | {r["sev_swagger"] or "not reported"} | {g} | '
               f'{r["tokens_in"]:,}/{r["tokens_out"]:,} | ${r["cost_usd"]:.3f} | {r["wall_min"]} min | '
               f'{"yes" if r["forced_report"] else "no"} |')
out += ["", "Tags per Nuclei call:", ""]
for r in rows:
    out.append(f'- run {r["run"]}: ' + "; ".join(",".join(t or []) for t in r["tags_per_call"]))
out += ["", "## Severity agreement across agent runs", "",
        f"- /metrics: {agree('sev_metrics')}", f"- Swagger: {agree('sev_swagger')}", "",
        "## Scripted baseline (no model)", "",
        "| Run | Status | Duration | Raw | Deduped | Prioritized | Found /metrics | Found Swagger |",
        "|---|---|---|---|---|---|---|---|"]
for b in base:
    out.append(f'| {b["run"]} | {b["status"]} | {round(b["duration_s"]/60,1)} min | {b["raw_count"]} | '
               f'{b["deduped_count"]} | {b["prioritized_count"]} | {"Y" if b["found_metrics"] else "N"} | '
               f'{"Y" if b["found_swagger"] else "N"} |')
if rows:
    c = [r["cost_usd"] for r in rows]; w = [r["wall_min"] for r in rows]
    out += ["", f"Agent cost range: ${min(c):.3f} to ${max(c):.3f} per run. "
                f"Agent wall-clock range: {min(w)} to {max(w)} min."]
text = "\n".join(out) + "\n"
open(f"{D}/TABLE.md", "w").write(text)
print(text)
